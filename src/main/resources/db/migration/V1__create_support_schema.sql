CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE CHECK (length(btrim(name)) > 0)
);

CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),
    email VARCHAR(160) NOT NULL UNIQUE,
    role VARCHAR(12) NOT NULL CHECK (role IN ('REQUESTER', 'AGENT')),
    department_id BIGINT NOT NULL REFERENCES departments(id),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL CHECK (length(btrim(name)) > 0),
    department_id BIGINT NOT NULL REFERENCES departments(id),
    UNIQUE (department_id, name)
);

CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(140) NOT NULL CHECK (length(btrim(title)) > 0),
    description VARCHAR(4000) NOT NULL CHECK (length(btrim(description)) > 0),
    requester_id BIGINT NOT NULL REFERENCES app_users(id),
    category_id BIGINT NOT NULL REFERENCES categories(id),
    assigned_agent_id BIGINT REFERENCES app_users(id),
    priority VARCHAR(12) NOT NULL CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    status VARCHAR(16) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    due_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ,
    closed_at TIMESTAMPTZ,
    archived_at TIMESTAMPTZ,
    CHECK (due_at > created_at),
    CHECK (updated_at >= created_at),
    CHECK ((status IN ('RESOLVED', 'CLOSED')) = (resolved_at IS NOT NULL)),
    CHECK ((status = 'CLOSED') = (closed_at IS NOT NULL)),
    CHECK (resolved_at IS NULL OR resolved_at >= created_at),
    CHECK (closed_at IS NULL OR closed_at >= resolved_at),
    CHECK (archived_at IS NULL OR status = 'CLOSED')
);

CREATE TABLE ticket_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets(id),
    actor_id BIGINT NOT NULL REFERENCES app_users(id),
    event_type VARCHAR(24) NOT NULL CHECK (event_type IN ('CREATED', 'ASSIGNED', 'STATUS_CHANGED', 'COMMENT_ADDED', 'ARCHIVED')),
    previous_status VARCHAR(16),
    new_status VARCHAR(16),
    message VARCHAR(2000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
